IF OBJECT_ID('tempdb.dbo.#PARTE1') IS NOT NULL BEGIN DROP TABLE #PARTE1 END
    SELECT 
        [ALA-FI-MATRICULA]
        ,[ALA-FI-DATA-ATUALIZACAO]
        ,[COMPETENCIA-FI]
        ,[TIPO-CARGO-FI]
        ,[COD-RUBRICA-FI]
        ,[DATA-INICIO-FI]
        ,[ALA-FI-ATIVO-INATIVO]
        ,[INFORMADO-FI]
        ,[OCORRIDO-FI]
        ,[ALA-FI-VALOR]
        ,[ALA-FI-PERC-PONT-DIA-HORA]
        ,[ALA-FI-RETROATIVO]
        ,[ALA-FI-SITUACAO-RUBRICA]
        ,[ALA-FI-PERC-HORA-EXTRA]
        ,[ALA-FI-QTDE-URV]
        ,[Origem]
        ,CASE WHEN [COD-RUBRICA-FI] > 0     AND [COD-RUBRICA-FI] < 100  THEN [ALA-FI-VALOR] ELSE 0 END  AS [PROVENTO]
        ,CASE WHEN [COD-RUBRICA-FI] >= 100  AND [COD-RUBRICA-FI] <= 400 THEN [ALA-FI-VALOR] ELSE 0 END  AS [DESCONTO]
INTO #PARTE1
FROM [pms_rhfp_desenvolvimento].[dbo].[rhfp_DADOS_FINANCEIROS]
WHERE [ALA-FI-MATRICULA] = 112607 AND [COMPETENCIA-FI] LIKE '2000%'
 
IF OBJECT_ID('tempdb.dbo.#PARTE2') IS NOT NULL BEGIN DROP TABLE #PARTE2 END
SELECT 
      [ALA-FI-MATRICULA]
    , [COMPETENCIA-FI]
    , [TIPO-CARGO-FI]
    , [COD-RUBRICA-FI]
    , [INFORMADO-FI]
    , [ALA-FI-VALOR]
    , [ALA-FI-PERC-PONT-DIA-HORA] 
    , [Origem]
    , [PROVENTO]
    , [DESCONTO]
    , SUM( [PROVENTO] ) OVER(
        PARTITION BY [ALA-FI-MATRICULA], [COMPETENCIA-FI], [TIPO-CARGO-FI] 
    ) AS [TOTAL_PROVENTO]
    , SUM( [DESCONTO] ) OVER(
        PARTITION BY [ALA-FI-MATRICULA], [COMPETENCIA-FI], [TIPO-CARGO-FI] 
    ) AS [TOTAL_DESCONTO]
INTO #PARTE2
FROM #PARTE1

IF OBJECT_ID('tempdb.dbo.#PARTE3') IS NOT NULL BEGIN DROP TABLE #PARTE3 END
SELECT 
      [ALA-FI-MATRICULA]
    , [COMPETENCIA-FI]
    , [TIPO-CARGO-FI]
    , [COD-RUBRICA-FI]
    , [INFORMADO-FI]
    , [ALA-FI-VALOR]
    , [ALA-FI-PERC-PONT-DIA-HORA] 
    , [Origem]
    , [PROVENTO]
    , [DESCONTO]
    , [TOTAL_PROVENTO]
    , [TOTAL_DESCONTO]
    , ([TOTAL_PROVENTO] - [TOTAL_DESCONTO])  AS [LIQUIDO]
INTO #PARTE3
FROM #PARTE2
 
SELECT 
      [ALA-FI-MATRICULA]
    , [COMPETENCIA-FI]
    , [TIPO-CARGO-FI] 
    , [TOTAL_PROVENTO]
    , [TOTAL_DESCONTO]
    , [LIQUIDO]
FROM #PARTE3
GROUP BY 
      [ALA-FI-MATRICULA]
    , [COMPETENCIA-FI]
    , [TIPO-CARGO-FI] 
    , [TOTAL_PROVENTO]
    , [TOTAL_DESCONTO]
    , [LIQUIDO]
ORDER BY [COMPETENCIA-FI] ASC, [TIPO-CARGO-FI] ASC;

